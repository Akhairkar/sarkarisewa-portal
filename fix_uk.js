  const filePath = 'data/states.json';
  const data = JSON.parse(fs.readFileSync(filePath, 'utf8'));

  let found = false;
  for (const state of data.states) {
    if (state.services) {
      const uk = state.services.find(s => s.id === 'uk-ration-card');
      if (uk) {
        uk.seoTitle = "उत्तराखंड राशन कार्ड 2026: नई लिस्ट, ऑनलाइन आवेदन और फायदे (Apply Now)";
        uk.seoDescription = "उत्तराखंड में राशन कार्ड के लिए ऑनलाइन आवेदन कैसे करें? NFSA नई लिस्ट 2026 देखें। जानिए पात्रता, आवश्यक दस्तावेज और 100% फ्री राशन योजना के बड़े फायदे।";
        uk.content = [
          {
            "type": "html",
            "html": "<p><strong>उत्तराखंड राशन कार्ड (Uttarakhand Ration Card)</strong> खाद्य, नागरिक आपूर्ति और उपभोक्ता मामले विभाग द्वारा जारी एक अत्यंत महत्वपूर्ण दस्तावेज़ है। राष्ट्रीय खाद्य सुरक्षा अधिनियम (NFSA) 2013 के तहत, यह कार्ड उत्तराखंड के गरीब और मध्यम वर्गीय परिवारों को बेहद रियायती दरों पर (या कुछ योजनाओं के तहत बिल्कुल मुफ्त) गेहूं, चावल, चीनी और मिट्टी का तेल जैसी आवश्यक वस्तुएं प्रदान करता है। हाल ही में सरकार ने राशन कार्ड नियमों में कई बड़े बदलाव किए हैं, जिससे लाखों लोगों को सीधा फायदा मिल रहा है।</p><h3>राशन कार्ड क्यों ज़रूरी है? (प्रमुख लाभ)</h3><ul><li><strong>सब्सिडी वाला राशन:</strong> बाज़ार मूल्य से बहुत कम कीमत पर उच्च गुणवत्ता वाला अनाज।</li><li><strong>आधिकारिक पहचान पत्र:</strong> यह परिवार की पहचान और पते का एक वैध सरकारी प्रमाण है।</li><li><strong>अन्य सरकारी योजनाएं:</strong> आयुष्मान कार्ड, पेंशन योजनाओं और निवास प्रमाण पत्र (Domicile) बनवाने में राशन कार्ड की आवश्यकता होती है।</li><li><strong>मुफ्त गैस कनेक्शन:</strong> प्रधानमंत्री उज्ज्वला योजना (PMUY) के तहत मुफ्त रसोई गैस कनेक्शन प्राप्त करने के लिए।</li></ul><h3>उत्तराखंड राशन कार्ड के प्रकार</h3><p>उत्तराखंड सरकार मुख्य रूप से तीन प्रकार के राशन कार्ड जारी करती है:</p><ol><li><strong>AAY (अंत्योदय अन्न योजना):</strong> सबसे गरीब परिवारों (BPL से भी नीचे) के लिए गुलाबी कार्ड। इन्हें 35 किलो राशन मिलता है।</li><li><strong>BPL (गरीबी रेखा से नीचे):</strong> गरीबी रेखा से नीचे जीवन यापन करने वालों के लिए सफेद कार्ड।</li><li><strong>APL (गरीबी रेखा से ऊपर):</strong> गरीबी रेखा से ऊपर के परिवारों के लिए पीला कार्ड।</li></ol><h3>आवेदन के लिए आवश्यक दस्तावेज</h3><ul><li>परिवार के मुखिया की पासपोर्ट साइज फोटो।</li><li>परिवार के सभी सदस्यों के आधार कार्ड (Aadhaar Card)।</li><li>पते का प्रमाण (बिजली बिल, पानी का बिल, या वोटर आईडी)।</li><li>आय प्रमाण पत्र (Income Certificate) - विशेष रूप से BPL और AAY के लिए।</li><li>बैंक पासबुक की कॉपी।</li></ul>"
          }
        ];

        uk.faqs = [
          {
            "q": "उत्तराखंड में नए राशन कार्ड के लिए ऑनलाइन आवेदन कैसे करें?",
            "a": "आप उत्तराखंड के खाद्य विभाग के आधिकारिक पोर्टल (fcs.uk.gov.in) पर जाकर या अपने नजदीकी CSC (Common Service Center) के माध्यम से ऑनलाइन आवेदन कर सकते हैं।"
          },
          {
            "q": "राशन कार्ड की नई लिस्ट 2026 कैसे चेक करें?",
            "a": "fcs.uk.gov.in पर 'Ration Card Details' विकल्प चुनें, अपना जिला, ब्लॉक और राशन डीलर (FPS) चुनें। इसके बाद पूरी लिस्ट आपके सामने आ जाएगी।"
          },
          {
            "q": "क्या राशन कार्ड में नए सदस्य का नाम जोड़ा जा सकता है?",
            "a": "हाँ, शादी के बाद पत्नी का नाम या बच्चे के जन्म के बाद उसका नाम राशन कार्ड में ऑनलाइन या DSO कार्यालय जाकर जोड़ा जा सकता है।"
          }
        ];
        found = true;
        break;
      }
    }
  }

  if (found) {
    fs.writeFileSync(filePath, JSON.stringify(data, null, 2), 'utf8');
    console.log('Updated uk-ration-card in states.json successfully.');
  } else {
    console.log('uk-ration-card not found in states.json.');
  }
